#define HUFF_SEG_MAXLEN (2 + 2 + 4 * 17 + 12 + 12 + 162 + 162)
static uint8_t g_dht_segment[HUFF_SEG_MAXLEN];
static size_t g_dht_segment_len = 0;

const uint8_t *mjpeg_get_default_dht_segment(size_t *out_len) {
  if (!g_dht_segment_len) {
    struct {
      uint8_t tcth;
      const uint8_t *bits17;
      const uint8_t *val;
      size_t val_n;
    } tabs[4] = {
        {0x00, dc_lumi_len, dc_lumi_val, sizeof(dc_lumi_val)},
        {0x01, dc_chromi_len, dc_chromi_val, sizeof(dc_chromi_val)},
        {0x10, ac_lumi_len, ac_lumi_val, sizeof(ac_lumi_val)},
        {0x11, ac_chromi_len, ac_chromi_val, sizeof(ac_chromi_val)},
    };
    uint8_t *p = g_dht_segment;
    *p++ = 0xFF;
    *p++ = 0xC4;
    uint8_t *len_field = p; /* patched below, once the segment size is known */
    p += 2;
    for (int t = 0; t < 4; t++) {
      *p++ = tabs[t].tcth;
      memcpy(p, tabs[t].bits17 + 1, 16); /* skip the len-0 padding entry */
      p += 16;
      memcpy(p, tabs[t].val, tabs[t].val_n);
      p += tabs[t].val_n;
    }
    size_t seg_len = (size_t)(p - g_dht_segment) - 2; /* excludes the FF C4 marker bytes */
    len_field[0] = (uint8_t)(seg_len >> 8);
    len_field[1] = (uint8_t)(seg_len & 0xFF);
    g_dht_segment_len = (size_t)(p - g_dht_segment);
  }
  *out_len = g_dht_segment_len;
  return g_dht_segment;
}

int find_jpeg_markers(const uint8_t *d, size_t n, int *has_dht,
                       size_t *sos_off) {
  *has_dht = 0;
  *sos_off = 0;
  if (n < 4 || d[0] != 0xFF || d[1] != 0xD8)
    return 0;
  size_t i = 2;
  while (i + 1 < n) {
    if (d[i] != 0xFF) {
      i++;
      continue;
    }
    uint8_t marker = d[i + 1];
    if (marker == 0x00 || marker == 0xFF) {
      i++;
      continue;
    }
    if (marker == 0x01 || marker == 0xD8 || marker == 0xD9 ||
        (marker >= 0xD0 && marker <= 0xD7)) {
      i += 2; /* TEM/SOI/EOI/RSTn: no length field */
      continue;
    }
    if (i + 3 >= n)
      return 0;
    size_t seg_len = ((size_t)d[i + 2] << 8) | d[i + 3];
    if (seg_len < 2)
      return 0;
    if (marker == 0xC4)
      *has_dht = 1;
    if (marker == 0xDA) {
      *sos_off = i;
      return 1;
    }
    i += 2 + seg_len;
  }
  return 0;
}
